function tupleToVocab(tuple: GoetheSeedTuple): Vocab {
  const [level, lemma, display, article] = tuple;
  const source = getGoetheSource(level);
  const partOfSpeech = inferPartOfSpeech(display, lemma, article);
  const koreanGloss = getDraftKoreanGloss(lemma, display);
  const vocab: Vocab = {
    id: `${source}-${slugGerman(lemma)}`,
    level,
    source,
    lemma,
    display,
    koreanGloss: koreanGloss.text,
    partOfSpeech,
    article,
    plural: partOfSpeech === "noun" ? inferPlural(display) : undefined,
    tags: ["goethe", level.toLocaleLowerCase("de-DE"), "draft-translation"],
    pronunciation: {
      lang: "de-DE",
      ttsText: article ? `${article} ${lemma}` : cleanTtsText(lemma),
      slowRate: 0.75,
    },
    translationStatus: "llm-draft",
    createdAt: SEED_TIMESTAMP,
    updatedAt: SEED_TIMESTAMP,
  };

  return withVocabQuality(vocab, {
    translation: koreanGloss.quality,
    partOfSpeechSource: "rule-inferred",
  });
}

function getDraftKoreanGloss(lemma: string, display: string) {
  const cleanedLemma = cleanLookupText(lemma);
  const cleanedDisplay = cleanLookupText(display);
  const directGloss =
    DRAFT_KOREAN_GLOSSES[lemma] ??
    DRAFT_VERB_GLOSSES[lemma] ??
    DRAFT_NOUN_GLOSSES[lemma] ??
    EXTRA_DRAFT_GLOSSES[lemma] ??
    DRAFT_KOREAN_GLOSSES[cleanedLemma] ??
    DRAFT_VERB_GLOSSES[cleanedLemma] ??
    DRAFT_NOUN_GLOSSES[cleanedLemma] ??
    EXTRA_DRAFT_GLOSSES[cleanedLemma];

  if (directGloss) {
    return { text: directGloss, quality: "llm-draft" as const };
  }

  const displayHead = cleanLookupText(
    cleanedDisplay.replace(/^(der|die|das)\s+/u, "").split(",")[0] ?? "",
  );
  const displayGloss =
    DRAFT_NOUN_GLOSSES[displayHead] ??
    DRAFT_VERB_GLOSSES[displayHead] ??
    DRAFT_KOREAN_GLOSSES[displayHead] ??
    EXTRA_DRAFT_GLOSSES[displayHead];

  if (displayGloss) {
    return { text: displayGloss, quality: "llm-draft" as const };
  }

  const compoundGloss = inferCompoundGloss(cleanedLemma);

  if (compoundGloss) {
    return { text: compoundGloss, quality: "rule-inferred" as const };
  }

  return {
    text: `${cleanedLemma} (초벌 번역)`,
    quality: "needs-review" as const,
  };
}

function inferCompoundGloss(lemma: string) {
  const normalizedLemma = lemma.toLocaleLowerCase("de-DE");
  const compoundParts: Array<[string, string]> = [
    ["zimmer", "방"],
    ["karte", "카드, 표"],
    ["essen", "식사"],
    ["bahn", "철도"],
    ["straße", "도로"],
    ["platz", "장소"],
    ["haus", "집"],
    ["geld", "돈"],
    ["arbeit", "일"],
    ["schule", "학교"],
    ["sprache", "언어"],
    ["zeit", "시간"],
    ["tag", "날"],
    ["name", "이름"],
    ["brief", "편지"],
    ["markt", "시장"],
    ["stadt", "도시"],
    ["bad", "욕실, 목욕"],
    ["wagen", "차"],
    ["führer", "안내자, 안내서"],
    ["schein", "증명서, 지폐"],
    ["stelle", "자리, 지점"],
    ["werk", "작업, 작품"],
    ["zeug", "도구, 물건"],
  ];
  const match = compoundParts.find(([suffix]) => normalizedLemma.endsWith(suffix));

  return match?.[1];
}

function cleanLookupText(value: string) {
  return value
    .replace(/^(der|die|das)\s+/u, "")
    .replace(/\s*\([^)]*\)\s*/gu, " ")
    .replace(/[,;].*$/u, "")
    .replace(/[–-]$/u, "")
    .replace(/\s+/gu, " ")
    .trim();
}

function getGoetheSource(level: "A1" | "A2"): VocabSource {
  return level === "A1" ? "goethe-a1" : "goethe-a2";
}

function createVocabKey(vocab: Pick<Vocab, "level" | "source" | "lemma">) {
  return `${vocab.level}:${vocab.source}:${slugGerman(vocab.lemma)}`;
}

function inferPartOfSpeech(
  display: string,
  lemma: string,
  article?: Article,
): PartOfSpeech {
  if (article) {
    return "noun";
  }

  if (/^[A-ZÄÖÜ]/u.test(display)) {
    return "noun";
  }

  const normalizedLemma = lemma.toLocaleLowerCase("de-DE");

  if (
    normalizedLemma.endsWith("en") ||
    normalizedLemma.endsWith("ern") ||
    normalizedLemma.endsWith("eln") ||
    display.includes("(sich)") ||
    normalizedLemma.startsWith("sich ")
  ) {
    return "verb";
  }

  if (display.includes(" ") || display.includes("/")) {
    return "phrase";
  }

  return "other";
}

function inferPlural(display: string) {
  const plural = display.split(",").slice(1).join(",").trim();

  return plural || undefined;
}

function cleanTtsText(lemma: string) {
  return lemma
    .replace(/^\(sich\)\s*/u, "")
    .replace(/[()]/gu, "")
    .replace(/\s+/gu, " ")
    .trim();
}

function slugGerman(value: string) {
  return value
    .toLocaleLowerCase("de-DE")
    .replace(/ä/gu, "ae")
    .replace(/ö/gu, "oe")
    .replace(/ü/gu, "ue")
    .replace(/ß/gu, "ss")
    .replace(/[^a-z0-9]+/gu, "-")
    .replace(/^-|-$/gu, "") || "entry";
}
